def attribute_duplicates(header: list[str]) -> list[str]:
    """중복 헤더에 '앞 문항 귀속' 꼬리표를 붙인다.

    WALLA 설문 도구는 이유 컬럼 헤더를 부모 문항 없이 '이유' / '위와 같이 평가한
    이유는 무엇인가요?' 로만 내보낸다. 5종 전부에 있고(리바랩스 22 · 케어클 15 ·
    이젠오토 13 · 정리습관 15 · 투블럭 3), 그대로 두면 같은 문장이 여러 행에 똑같이
    앉아 어느 문항의 이유인지 시트만 봐서는 알 수 없다 — 분류 에이전트가 틀리는 자리다.
    이유 컬럼은 항상 부모 척도 문항 바로 뒤에 오므로 직전의 고유 헤더로 귀속시킨다.
    """
    dup = {h for h in header if header.count(h) > 1 and h}
    out, parent = [], ""
    for h in header:
        if h and h not in dup:
            parent = h
            out.append(h)
        elif h in dup and parent:
            out.append(f"{h}  ※ 앞 문항 귀속: {parent}")
        else:
            out.append(h)
    return out


def build_rows() -> list[dict]:
    """단계매핑 행 전체. sync-stage-sheet.py 도 이걸 그대로 쓴다."""
    rows = []
    for ds, fname in FILES.items():
        header = read_header(DATA / fname)
        for i, text in HEADER_OVERRIDE.get(ds, {}).items():
            header[i] = text
        header = [h.replace("(copy)", "").strip() for h in header]
        header = attribute_duplicates(header)
        seen = set()
        for start, end, key in SPEC[ds]:
            code, name, sub, _, layout = STAGE[key]
            for i in range(start, min(end + 1, len(header))):
                seen.add(i)
                rows.append({
                    "단계코드": code, "단계명": name, "하위유형": sub, "데이터셋": ds,
                    "컬럼번호": i,
                    "raw data 컬럼 헤더(문항 원문)": header[i] or "(빈 열)",
                    "레이아웃 코드": layout,
                    "_sub": STAGE[key][3],
                })
        missing = [i for i in range(len(header)) if i not in seen]
        assert not missing, f"{ds}: 미배정 인덱스 {missing}"

    rows.sort(key=lambda r: (r["단계코드"], r["_sub"], DS_ORDER.index(r["데이터셋"]),
                             r["컬럼번호"]))
    # 몇 개 제품군에 나타나는 단계인지 — 전 제품군에 있으면 필수 골격으로 본다.
    cover = collections.defaultdict(set)
    for r in rows:
        cover[r["단계코드"]].add(r["데이터셋"])
    for r in rows:
        n = len(cover[r["단계코드"]])
        r["전 제품군 공통"] = ("미출력" if r["단계코드"] == "S0"
                          else f"{'필수' if n == len(FILES) else '조건부'} {n}/{len(FILES)}")
    return rows


