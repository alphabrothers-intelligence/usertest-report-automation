def read_header(path: Path) -> list[str]:
    if path.suffix == ".xlsx":
        ws = openpyxl.load_workbook(path, read_only=True).worksheets[0]
        cells = next(ws.iter_rows(max_row=1))
        return [" ".join(str(c.value or "").split()) for c in cells]
    with path.open(encoding="utf-8-sig") as f:
        return [" ".join(c.split()) for c in next(csv.reader(f))]


def main() -> None:
    rows = []
    for ds, fname in FILES.items():
        header = read_header(DATA / fname)
        for i, text in HEADER_OVERRIDE.get(ds, {}).items():
            header[i] = text
        header = [h.replace("(copy)", "").strip() for h in header]
        seen = set()
        for start, end, key in SPEC[ds]:
            code, name, sub, _, layout = STAGE[key]
            for i in range(start, min(end + 1, len(header))):
                seen.add(i)
                rows.append({
                    "단계코드": code, "단계명": name, "하위유형": sub, "데이터셋": ds,
                    "컬럼번호": i,
                    "raw data 컬럼 헤더(문항 원문)": header[i] or "(빈 열)",
                    "레이아웃 코드": layout,
                    "_sub": STAGE[key][3],
                })
        missing = [i for i in range(len(header)) if i not in seen]
        assert not missing, f"{ds}: 미배정 인덱스 {missing}"

    rows.sort(key=lambda r: (r["단계코드"], r["_sub"], DS_ORDER.index(r["데이터셋"]),
                             r["컬럼번호"]))
    # 몇 개 제품군에 나타나는 단계인지 — 전 제품군에 있으면 필수 골격으로 본다.
    cover = collections.defaultdict(set)
    for r in rows:
        cover[r["단계코드"]].add(r["데이터셋"])
    for r in rows:
        n = len(cover[r["단계코드"]])
        r["전 제품군 공통"] = ("미출력" if r["단계코드"] == "S0"
                          else f"{'필수' if n == len(FILES) else '조건부'} {n}/{len(FILES)}")

    fields = ["단계코드", "단계명", "하위유형", "데이터셋", "컬럼번호",
              "raw data 컬럼 헤더(문항 원문)", "레이아웃 코드", "전 제품군 공통"]
    with (DOCS / "NOTION_STAGE_MAPPING.csv").open("w", newline="", encoding="utf-8-sig") as f:
        w = csv.DictWriter(f, fields, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)

    with (DOCS / "NOTION_LAYOUT_CATALOG.csv").open("w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow(["레이아웃 코드", "레이아웃 이름", "분류", "형태 설명", "사용 단계", "생성 조건"])
        w.writerows(LAYOUTS)

    # xlsx는 담당자가 직접 넣은 예시 이미지·행 높이를 갖고 있어 덮어쓰면 날아간다.
    # 백지에서 다시 만들 때만 --xlsx.
    if "--xlsx" in sys.argv:
        write_xlsx(rows, fields)
    print(f"매핑 {len(rows)}행 · 레이아웃 {len(LAYOUTS)}행 재생성 완료"
          f"{'' if '--xlsx' in sys.argv else ' (csv만 — xlsx는 --xlsx)'}")


# 단계코드별 배경색 (S0는 회색, 나머지는 파스텔 순환)
STAGE_FILL = {
    "S0": "D9D9D9", "S1": "DDEBF7", "S2": "E2EFDA", "S3": "FCE4D6", "S4": "FFF2CC",
    "S5": "E4DFEC", "S6": "DDEBF7", "S7": "E2EFDA", "S8": "FCE4D6", "S9": "FFF2CC",
}


def write_xlsx(rows: list[dict], fields: list[str]) -> None:
    """엑셀 파일 1개에 시트 2개(단계매핑 · 레이아웃). 반복 값은 세로 병합."""
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
    from openpyxl.utils import get_column_letter

    thin = Side(style="thin", color="BFBFBF")
    box = Border(left=thin, right=thin, top=thin, bottom=thin)
    head_font = Font(bold=True, size=11)
    head_fill = PatternFill("solid", fgColor="FFF2A8")
    center = Alignment(horizontal="center", vertical="center", wrap_text=True)
    left = Alignment(horizontal="left", vertical="center", wrap_text=True)

    wb = Workbook()

    # --- 시트 1: 단계매핑 -------------------------------------------------
    ws = wb.active
    ws.title = "단계매핑"
    ws.append(fields)
    for r in rows:
        ws.append([r[f] for f in fields])

    for c, w in enumerate([10, 26, 24, 20, 10, 78, 44], start=1):
        ws.column_dimensions[get_column_letter(c)].width = w
    for cell in ws[1]:
        cell.font, cell.fill, cell.alignment, cell.border = head_font, head_fill, center, box

    for row in ws.iter_rows(min_row=2):
        for cell in row:
            cell.border = box
            cell.alignment = center if cell.column <= 5 else left
        fill = STAGE_FILL.get(row[0].value)
        if fill:
            for cell in row[:3]:
                cell.fill = PatternFill("solid", fgColor=fill)

    # 반복 값 세로 병합 — 열마다 상위 열까지 같아야 한 덩어리로 본다
    for col, key_cols in ((1, [0]), (2, [0]), (3, [0, 2]), (4, [0, 2, 3])):
        start, prev = 2, None
        for i, r in enumerate(rows, start=2):
            cur = tuple(r[fields[k]] for k in key_cols)
            if cur != prev:
                if prev is not None and i - start > 1:
                    ws.merge_cells(start_row=start, start_column=col,
                                   end_row=i - 1, end_column=col)
                start, prev = i, cur
        if len(rows) + 2 - start > 1:
            ws.merge_cells(start_row=start, start_column=col,
                           end_row=len(rows) + 1, end_column=col)

    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:{get_column_letter(len(fields))}{len(rows) + 1}"

    # --- 시트 2: 레이아웃 -------------------------------------------------
    # 레이아웃 코드 → 단계매핑 시트에서 처음 등장하는 행 번호
    first_row = {}
    for i, r in enumerate(rows, start=2):
        for c in r["레이아웃 코드"].split("|"):
            first_row.setdefault(c, i)

    ws2 = wb.create_sheet("레이아웃")
    ws2.append(["레이아웃 코드", "레이아웃 이름", "분류", "예시 이미지", "형태 설명",
                "사용 단계", "생성 조건 · 판단 근거", "매핑 사용 행 수", "단계매핑에서 보기"])
    last = len(rows) + 1
    for code, name, kind, shape, stages, cond in LAYOUTS:
        # 구분자를 양쪽에 붙여 부분일치를 막는다 (L1이 L10·L11까지 세지 않도록)
        n = ws2.max_row + 1
        ws2.append([code, name, kind, None, shape, stages, cond,
                    f'=SUMPRODUCT(--ISNUMBER(SEARCH("|"&A{n}&"|",'
                    f'"|"&단계매핑!$G$2:$G${last}&"|")))', None])

    for c, w in enumerate([14, 22, 8, 40, 46, 34, 62, 14, 18], start=1):
        ws2.column_dimensions[get_column_letter(c)].width = w
    for cell in ws2[1]:
        cell.font, cell.fill, cell.alignment, cell.border = head_font, head_fill, center, box

    kind_fill = {"차트": "E2EFDA", "표": "DDEBF7", "헤더": "FCE4D6",
                 "텍스트": "FFF2CC", "기타": "D9D9D9"}
    for row in ws2.iter_rows(min_row=2):
        for cell in row:
            cell.border = box
            cell.alignment = left if cell.column in (5, 6, 7) else center
        row[0].font = Font(bold=True)
        row[2].fill = PatternFill("solid", fgColor=kind_fill.get(row[2].value, "FFFFFF"))
        target = first_row.get(row[0].value)
        link = row[8]
        if target:
            link.value = f"→ {target}행 보기"
            link.hyperlink = f"#단계매핑!A{target}"
            link.font = Font(color="0563C1", underline="single")
        else:
            link.value = "매핑에 사용 안 됨"
            link.font = Font(color="808080", italic=True, size=9)

    embed_images(ws2)
    ws2.freeze_panes = "A2"
    ws2.auto_filter.ref = f"A1:I{len(LAYOUTS) + 1}"

    wb.save(DOCS / "NOTION_STAGE_MAPPING.xlsx")


# 표·텍스트 레이아웃은 hwpx에 이미지가 아니라 표 객체로 들어 있어 추출이 안 된다.
NO_IMAGE = "발행 보고서에 표·텍스트 객체로 들어 있어 이미지 추출 불가"


def embed_images(ws) -> None:
    """docs/layout-images/{코드}.png 를 '예시 이미지' 열에 끼워 넣는다."""
    from openpyxl.drawing.image import Image as XLImage
    from openpyxl.styles import Font
    from PIL import Image as PILImage

    src = DOCS / "layout-images"
    THUMB_W = 260  # px

    for row in ws.iter_rows(min_row=2):
        code = row[0].value
        path = src / f"{code}.png"
        cell = row[3]

        # 여러 줄짜리 '생성 조건'이 잘리지 않도록 줄 수만큼 높이를 준다.
        # 열 너비(62)를 넘는 줄은 한 번 더 접히므로 넉넉히 잡는다.
        lines = sum(max(1, len(ln) // 55 + 1) for ln in str(row[6].value).split("\n"))
        text_h = lines * 15 + 8

        if not path.exists():
            cell.value = NO_IMAGE
            cell.font = Font(color="808080", italic=True, size=9)
            ws.row_dimensions[cell.row].height = text_h
            continue

        with PILImage.open(path) as im:
            h = max(1, round(im.height * THUMB_W / im.width))
        img = XLImage(path)
        img.width, img.height = THUMB_W, h
        img.anchor = cell.coordinate
        ws.add_image(img)
        ws.row_dimensions[cell.row].height = max(h * 0.78 + 6, text_h)  # px → point


if __name__ == "__main__":
    main()